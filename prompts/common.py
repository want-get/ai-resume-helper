# === 面试通用规则 ===
# 用于模拟面试的 system prompt，规定面试官的行为准则
INTERVIEW_RULES = """1. 每次只提一个问题
2. 候选人回答后，要先给出评价（优点和不足），然后提出下一个问题
3. 问题要循序渐进，从简单到深入
4. 评价要具体，要有建设性的改进建议
5. 面试问题要围绕简历内容展开
6. 总共问 5 个左右的问题，最后给出总体评价"""


# === 简历评分维度与权重 ===
# 用于简历评分，规定各维度的满分
SCORE_CRITERIA = """1. 基本信息完整性（15分）
2. 教育背景（15分）
3. 工作/实习经历（30分）
4. 项目经验（25分）
5. 技能与证书（15分）"""


# === 简历优化通用要求 ===
# 用于简历优化，规定优化的通用准则
RESUME_OPTIMIZE_RULES = """1. 改进措辞，使用更专业、更有说服力的表达
2. 量化成果，突出关键数据和业绩（如果原简历没有数据，可以根据岗位特点合理建议添加）
3. 按 STAR 法则（情境-任务-行动-结果）重新组织项目经历描述
4. 找出简历中的薄弱环节，给出 3 条具体的改进建议
5. 保持真实，不要编造不存在的经历"""