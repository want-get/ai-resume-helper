"""系统级 Prompt 模板：防幻觉、RAG 引用、长上下文摘要、工具调用。

这些模板贯穿整个后端，是「防幻觉机制」的第一道防线：
    * 明确告诉模型「只依据给定资料作答」
    * 资料没有覆盖时必须明说「资料中未提及」，禁止脑补
    * 强制输出 ``[1]`` ``[2]`` 形式的引用编号，便于后置校验
"""

from __future__ import annotations

# ====================================================================== #
# 一、防幻觉通用约束
# ====================================================================== #
ANTI_HALLUCINATION_RULES = """【事实性约束（必须严格遵守）】
1. 只能依据下面「参考资料」中的内容作答，不得使用参考资料之外的知识补充事实。
2. 参考资料没有涉及的内容，必须明确回答「参考资料中未提及」，禁止推测、编造或凭印象补充。
3. 禁止编造具体数字、公司名、人名、时间、薪资区间、录用比例等可验证信息。
4. 引用参考资料时，在对应句子末尾标注来源编号，格式为 [1]、[2]，可同时标注多个如 [1][3]。
5. 不要提及「参考资料」「上下文」这类字眼来描述材料本身，直接把内容讲清楚即可。
6. 如果参考资料相互矛盾，要指出矛盾点，而不是擅自选一个当作结论。
7. 如果资料不足，先说明「资料不足」，再说明还缺什么信息。"""


# ====================================================================== #
# 二、RAG 问答（知识库检索增强生成）
# ====================================================================== #
